def process_and_merge_folder(folder_name, batch_prefix):
    src_dir = os.path.join(base_dir, folder_name)
    copied_count = 0

    if not os.path.exists(src_dir):
        print(f"[!] Warning: Directory not found - {src_dir}")
        return 0

    for filename in os.listdir(src_dir):
        if filename.lower().endswith(('.jpg', '.jpeg', '.png')):
            src_path = os.path.join(src_dir, filename)

            # Sort into subfolders based on the label in the filename (0_ or 1_)
            if filename.startswith("0_"):
                target_dir = male_dir
            elif filename.startswith("1_"):
                target_dir = female_dir
            else:
                print(f"[!] Unknown label format for file: {filename}")
                continue

            # Create a new unique filename to prevent overwriting
            # Example: "0_145.jpg" -> "dot_1_0_145.jpg"
            new_filename = f"{batch_prefix}_{filename}"
            dest_path = os.path.join(target_dir, new_filename)

            # Copy the file to the new destination safely
            shutil.copy2(src_path, dest_path)
            copied_count += 1

    return copied_count

